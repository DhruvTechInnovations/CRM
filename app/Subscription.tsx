import { paymentService } from '../services/apiService';

// Placeholder for your Razorpay API Key ID (e.g., rzp_test_xxxxx)
const RAZORPAY_KEY_ID = 'rzp_test_SjDChXI2EGWTTh';

export default function Subscription() {
  const router = useRouter();
  const [loading, setLoading] = useState(false);

  // Example subscription plans
  const plans = [
    {
      id: 'prod_101',
      name: 'Basic Plan',
      price: 499,
      duration: '1 Month',
      features: ['Access to basic features', 'Email support', '1 User license'],
    },
    {
      id: 'prod_102',
      name: 'Premium Plan',
      price: 4999,
      duration: '1 Year',
      features: ['All Basic features', 'Priority 24/7 support', 'Unlimited User licenses', 'Advanced Analytics'],
    },
  ];

  const handleSubscribe = async (plan: { id: any; name: any; price: any; duration?: string; features?: string[]; }) => {
    try {
      setLoading(true);

      // 1. Create order on the backend
      // Provide plan details to backend so it can generate an amount-specific order
      const orderResponse = await paymentService.createRazorpayOrder({
        planId: plan.id,
        amount: plan.price * 100, // typically amount is in paise
      });

      console.log('orderResponse ', orderResponse)

      if (!orderResponse || !orderResponse.data.order_id) {
        throw new Error('Failed to create order from server.');
      }

      const options = {
        description: `Subscription for ${plan.name}`,
        image: 'https://jplawsuvidha.com/TLogo.png', // Add your actual logo URL here
        currency: 'INR',
        key: RAZORPAY_KEY_ID,
        amount: plan.price * 100,
        name: 'JPLegalConnect',
        order_id: orderResponse.data.order_id, // Generated by backend
        prefill: {
          email: 'user@example.com', // Prefill from user profile if available
          contact: '9999999999',     // Prefill from user profile if available
          name: 'John Doe'           // Prefill from user profile if available
        },
        theme: { color: '#0F62FE' }
      };

      // 2. Open Razorpay Checkout
      RazorpayCheckout.open(options)
        .then(async (data) => {
          // data contains razorpay_payment_id, razorpay_order_id, razorpay_signature
          // 3. Verify payment on the backend
          const verificationResponse = await paymentService.verifyPayment({
            razorpay_payment_id: data.razorpay_payment_id,
            razorpay_order_id: data.razorpay_order_id,
            razorpay_signature: data.razorpay_signature,
            planId: plan.id,
          });

          if (verificationResponse.success) {
            Alert.alert('Success', `You have successfully subscribed to ${plan.name}!`);
            router.replace('/(tabs)/Dashboard'); // Navigate to dashboard after success
          } else {
            Alert.alert('Verification Failed', 'Payment signature verification failed.');
          }
        })
        .catch((error) => {
          // Handle failure or cancellation
          console.log(error);
          Alert.alert('Payment Failed', error.description || 'Payment was cancelled or failed.');
        });
    } catch (err) {
      console.error(err);
      Alert.alert('Error', 'Unable to initiate payment. Please make sure backend endpoints and Razorpay keys are configured.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <SafeAreaView style={styles.safeArea}>
      <View style={styles.header}>
        <TouchableOpacity style={styles.backButton} onPress={() => router.back()}>
          <Ionicons name="arrow-back" size={24} color="#1F2937" />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>Subscription Plans</Text>
        <View style={{ width: 24 }} />
      </View>

      <ScrollView contentContainerStyle={styles.container}>
        <View style={styles.introContainer}>
          <Text style={styles.title}>Upgrade Your Experience</Text>
          <Text style={styles.subtitle}>
            Choose a plan that fits your needs to unlock all features.
          </Text>
        </View>

        {plans.map((plan) => (
          <View key={plan.id} style={styles.card}>
            <View style={styles.cardHeader}>
              <Text style={styles.planName}>{plan.name}</Text>
              <Text style={styles.planPrice}>₹{plan.price}</Text>
              <Text style={styles.planDuration}>/ {plan.duration}</Text>
            </View>

            <View style={styles.featuresContainer}>
              {plan.features.map((feature, idx) => (
                <View key={idx} style={styles.featureRow}>
                  <Ionicons name="checkmark-circle" size={20} color="#10B981" />
                  <Text style={styles.featureText}>{feature}</Text>
                </View>
              ))}
            </View>

            <TouchableOpacity
              style={styles.subscribeButton}
              onPress={() => handleSubscribe(plan)}
              disabled={loading}
            >
              <Text style={styles.subscribeButtonText}>Subscribe Now</Text>
            </TouchableOpacity>
          </View>
        ))}
      </ScrollView>

      {loading && (
        <View style={styles.loadingOverlay}>
          <ActivityIndicator size="large" color="#0F62FE" />
          <Text style={styles.loadingText}>Processing...</Text>
        </View>
      )}
    </SafeAreaView>
  );
}

